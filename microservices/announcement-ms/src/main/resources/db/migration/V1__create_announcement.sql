create table announcement (
    id           bigint generated by default as identity primary key,
    title        varchar(120)  not null,
    summary      varchar(280)  not null,
    body         varchar(4000) not null,
    category     varchar(20)   not null,
    status       varchar(20)   not null,
    published_at timestamp(6) with time zone,
    created_at   timestamp(6) with time zone not null,
    updated_at   timestamp(6) with time zone not null,
    created_by   varchar(100)  not null,
    constraint announcement_category_check check (category in ('GENERAL', 'TRAINING', 'EVENT', 'MAINTENANCE')),
    constraint announcement_status_check check (status in ('DRAFT', 'PUBLISHED'))
);

-- Public search: published announcements, newest first.
create index announcement_published_idx on announcement (status, published_at desc, id desc);
